// src/surveys/survey-questions.ts
//
// ЕДИНАЯ форма опроса (v1 unified).
// На старте используем только вопросы, которые уже полностью описаны в текущем файле (блок SMALL 1..32).
//
// Система баллов/риска:
// - score: 1..5 (как value в HTML)
// - points: score * 20 (шкала 20..100 для калькулятора)
// - weight: риск 0..1, где 1 = плохо (score=1), 0 = отлично (score=5)

export type QuestionType = 'select' | 'radio' | 'text'

export interface QuestionOption {
  id: 'v1' | 'v2' | 'v3' | 'v4' | 'v5'
  label: string
  score: 1 | 2 | 3 | 4 | 5
  points: number // score*20
  weight: number // 0..1 (1 = высокий риск)
}

export interface SurveyQuestion {
  id: string
  group: string // заголовок секции/группы
  categoryKey: string // machine key для аналитики
  text: string
  type: QuestionType
  required: boolean
  options: QuestionOption[]
}

function option(score: 1 | 2 | 3 | 4 | 5, label: string): QuestionOption {
  const weight = (5 - score) / 4 // 5->0; 1->1
  return {
    id: `v${score}` as QuestionOption['id'],
    label,
    score,
    points: score * 20,
    weight: Math.round(weight * 100) / 100,
  }
}

function select5(labelsByScore: { 5: string; 4: string; 3: string; 2: string; 1: string }): QuestionOption[] {
  return [
    option(5, labelsByScore[5]),
    option(4, labelsByScore[4]),
    option(3, labelsByScore[3]),
    option(2, labelsByScore[2]),
    option(1, labelsByScore[1]),
  ]
}

